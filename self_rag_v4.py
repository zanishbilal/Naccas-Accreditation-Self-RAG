def grade_generation_v_documents_and_question(state, similarity_threshold=0.5):
    print("---CHECK HALLUCINATIONS (COSINE SIMILARITY)---")
    question = state["question"]
    documents = state["documents"]
    generation = state["generation"]

    generation_embedding = embedding_model.embed_query(generation)
    doc_embeddings = [embedding_model.embed_query(doc.page_content) for doc in documents]
    similarities = [cosine_similarity([generation_embedding], [doc_emb])[0][0] for doc_emb in doc_embeddings]
    max_similarity = max(similarities) if similarities else 0.0
    print(f"→ MAX DOC SIMILARITY: {max_similarity:.4f}")

    if max_similarity >= similarity_threshold:
        print("→ GENERATION IS GROUNDED")
        query_embedding = embedding_model.embed_query(question)
        answer_similarity = cosine_similarity([generation_embedding], [query_embedding])[0][0]
        print(f"→ ANSWER SIMILARITY: {answer_similarity:.4f}")
        return "useful" if answer_similarity >= similarity_threshold else "not useful"
    else:
        print("→ GENERATION NOT GROUNDED, RE-TRY")
        return "not supported"

