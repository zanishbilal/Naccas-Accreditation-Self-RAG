def extract_qas_from_txt(path):
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()

    # Extract Python list-style variables using ast.literal_eval
    questions_block = content.split("questions =")[1].split("ground_truths =")[0].strip()
    truths_block = content.split("ground_truths =")[1].strip()

    questions = ast.literal_eval(questions_block)
    ground_truths = ast.literal_eval(truths_block)

    return questions, ground_truths

