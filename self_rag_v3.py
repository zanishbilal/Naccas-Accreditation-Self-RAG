# Improved QA extraction from .docx
def extract_qas(path):
    doc = Document(path)
    questions, truths = [], []
    q, t, mode = "", "", None

    for para in doc.paragraphs:
        text = para.text.strip()
        if not text:
            continue

        # Match lines like: 1 What is...? or 2)What...? or 3. What...?
        match = re.match(r'^(\d+)[\.\)]?\s*(.+)', text)
        if match:
            if q and t:
                questions.append(q.strip())
                truths.append(t.strip())
            q = match.group(2).strip()
            t, mode = "", None
        elif text.lower().startswith("ground truth"):
            mode = "truth"
        elif mode == "truth":
            t += " " + text.strip()

    if q and t:
        questions.append(q.strip())
        truths.append(t.strip())

    return questions, truths

